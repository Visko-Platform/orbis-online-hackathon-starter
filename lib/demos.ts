export const getDemo = (id: string) => DEMOS.find((d) => d.id === id);

/** Serializable subset of a Demo that can cross into Client Components (no functions). */
export type DemoView = Omit<Demo, "composeInstruction" | "uploadInstruction" | "subjectFromText"> & {
  subjectFromText?: { placeholder: string };
};

export function toView(demo: Demo): DemoView {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { composeInstruction, uploadInstruction, subjectFromText, ...rest } = demo;
  return subjectFromText ? { ...rest, subjectFromText: { placeholder: subjectFromText.placeholder } } : rest;
}
