// Demo definitions. Each demo is the same live engine with industry-specific
// assets, compose instructions, and one-click directions.
//
// Prompt rules (research/BRIEF.md): opening prompt = WHO + WHAT + WHERE + camera.
// Every direction = ONE visible change phrased as a state transition. No
// negation, no vague intent words.

export type DemoSubject = { id: string; label: string; src: string; /** A person photo: placed into the scene (upload instruction). */ person?: boolean };

export type DemoOption = {
  id: string;
  label: string;
  /** Product image, sent to Nano Banana and to the live-swap writer. */
  src?: string;
  /** Visual description used when there is no image (styles, locations). */
  text: string;
};

export type DemoChip = { group: string; label: string; prompt: string };

/**
 * A shot is generated by the frontier image model from the high-res hero
 * still (same subject, new angle or scenario), then fed to Orbis:
 *  - "cut":   reset -> set_image(shot) -> set_prompt(motion) -> start
 *  - "morph": set_prompt(text describing the shot) on the running stream
 */
export type DemoShot = {
  id: string;
  label: string;
  /** Image-edit instruction applied to the hero still. */
  instruction: string;
  /** Text supplement: what moves once Orbis runs from this shot. */
  motion: string;
};

export type Demo = {
  id: string;
  title: string;
  industry: string;
  tagline: string;
  pitch: string[];
  accent: string;
  subjectLabel: string;
  subjects: DemoSubject[];
  optionLabel: string;
  options: DemoOption[];
  /** Allow choosing several options for the composed look. */
  multiOption: boolean;
  /** Nano Banana instruction. Image 1 is the subject, later images are option images. */
  composeInstruction: (options: DemoOption[]) => string;
  /** What should happen once the stream starts. Gemini grounds it in the frame. */
  openingMotion: string;
  /** How the live-swap writer should phrase a swap. */
  swapGuidance: string;
  chips: DemoChip[];
  shots: DemoShot[];
  /** Timed sequences of directions (one steer per step). */
  scenarios?: DemoScenario[];
  /** Subjects can be multi-selected and placed on the shot board as a list. */
  multiSubject?: boolean;
  /** Label on the upload tile. */
  uploadLabel?: string;
  /** Hero instruction when the subject is a user upload (e.g. place a shopper's photo into the scene). */
  uploadInstruction?: (options: DemoOption[]) => string;
  /** Extra rules every Gemini-written Orbis prompt and every generated shot must follow. */
  directorRules?: string;
  /** "Put selected on shot board" renders a hero per subject first (e.g. furnish each room). */
  boardRendersSubjects?: boolean;
  /** Options selected by default (else the first option). */
  defaultOptionIds?: string[];
  /** Allow typing a subject (e.g. a city name); the hero is generated from text. */
  subjectFromText?: { placeholder: string; prompt: (text: string, options: DemoOption[]) => string };
  audioPrompt?: string;
};

